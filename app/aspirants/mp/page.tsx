export default function ConstituenciesPage() {
  const [search, setSearch] = useState("");

  const filtered = useMemo(() => {
    return constituencies.filter((c) =>
      c.name.toLowerCase().includes(search.toLowerCase()) ||
      c.county.toLowerCase().includes(search.toLowerCase())
    );
  }, [search]);

  return (
    <div className="page-wrapper">
      <h1 className="section-title">Constituencies</h1>
      <div className="constituency-search">
        <FiSearch className="search-icon" />
        <input
          type="text"
          placeholder="Search constituencies..."
          value={search}
          onChange={(e) => setSearch(e.target.value)}
          className="search-input"
        />
      </div>
      <div className="constituency-list">
        {filtered.map((c) => (
          <Link
            key={c.name}
            href={`/aspirants/constituency/${encodeURIComponent(c.name)}`}
            className="constituency-link"
          >
            {c.name}
            <span className="constituency-county">{c.county}</span>
          </Link>
        ))}
        {filtered.length === 0 && (
          <p className="constituency-empty">No constituencies found.</p>
        )}
      </div>
      <p className="constituency-count">
        {filtered.length} of {constituencies.length} constituencies
      </p>
    </div>
  );
}
